ejemplares = 15
prestamos = 20
print("Suma")
print(ejemplares, "+", prestamos, "=", ejemplares + prestamos)
print("Resta")
print(ejemplares, "-", prestamos, "=", ejemplares - prestamos)
print("Multiplicacion")
print(ejemplares, "*", prestamos, "=", ejemplares * prestamos)
print("Division")
print(ejemplares, "/", prestamos, "=", ejemplares / prestamos)
print("Potencia")
print(ejemplares, "**", prestamos, "=", ejemplares ** prestamos)
print("Division Entera")
print(ejemplares, "//", prestamos, "=", ejemplares // prestamos)
print("Modulo")
print(ejemplares, "%", prestamos, "=", ejemplares % prestamos)

